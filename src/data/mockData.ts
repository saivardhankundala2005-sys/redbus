// Helper to generate realistic bus seats
export function generateSeats(seed: number = 1): Seat[] {
  const seats: Seat[] = [];
  const rows = 10;
  const cols = [0, 1, 3, 4]; // 0,1 left of aisle; 2 is aisle; 3,4 right of aisle
  const colLetters = ['A', 'B', 'C', 'D'];

  for (let r = 1; r <= rows; r++) {
    cols.forEach((colIndex, i) => {
      const seatNum = `${r}${colLetters[i]}`;
      const isFrontRow = r === 1;
      const isExtraLegroom = r === 1 || r === 5;
      const isPreferred = isFrontRow || isExtraLegroom;
      
      // Deterministic pseudo-randomness for seat occupation based on seat number & seed
      const pseudoHash = (r * 7 + i * 13 + seed * 19) % 100;
      const isAvailable = pseudoHash > 42; // ~58% availability
      
      // Women reserved seats (strictly protected, never monetized)
      const isWomenOnly = (r === 2 || r === 3) && (colIndex === 0 || colIndex === 1);
      
      seats.push({
        id: `seat-${r}-${colIndex}`,
        seatNumber: seatNum,
        row: r,
        col: colIndex,
        deck: 'lower',
        type: 'seater',
        isAvailable,
        isWomenOnly,
        isPreferred,
        preferredFee: isPreferred ? 20 : 0,
        isJustFreed: false,
      });
    });
  }
  return seats;
}

